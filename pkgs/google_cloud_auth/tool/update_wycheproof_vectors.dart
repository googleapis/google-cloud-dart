/// Generates `test/verifier/wycheproof_vectors.dart` from the
/// [Project Wycheproof](https://github.com/C2SP/wycheproof) JSON Web Signature
/// test vectors.
///
/// We generate Dart code instead of loading the JSON test files because loading
/// the files at runtime isn't supported in the browser.
///
/// Run from the package directory:
///
/// ```shell
/// dart run tool/update_wycheproof_vectors.dart
/// ```
///
/// To update the vectors, change [_commit] and run this again.
library;

import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;

/// The C2SP/wycheproof commit to take the vectors from.
const _commit = 'e0df04e0c033f2d25c5051dd06230336c7822358';
const _vectorsPath = 'testvectors_v1/json_web_signature_test.json';
const _outputPath = 'test/verifier/wycheproof_vectors.dart';

/// Whether [group] has a public key that an RS256 verifier could use.
///
/// This includes keys with no `alg`, such as the encryption keys that
/// signature verification must reject.
bool _isRs256Group(Map<String, Object?> group) => switch (group['public']) {
  final Map<String, Object?> key =>
    key['kty'] == 'RSA' && (key['alg'] ?? 'RS256') == 'RS256',
  _ => false,
};

Future<void> main() async {
  final uri = Uri.https(
    'raw.githubusercontent.com',
    '/C2SP/wycheproof/$_commit/$_vectorsPath',
  );
  final response = await http.get(uri);
  if (response.statusCode != 200) {
    throw Exception('Failed to fetch $uri: ${response.statusCode}');
  }

  final vectors = jsonDecode(response.body) as Map<String, Object?>;
  final groups = [
    for (final group
        in (vectors['testGroups']! as List).cast<Map<String, Object?>>())
      if (_isRs256Group(group))
        // The private keys aren't needed to verify signatures.
        {
          'comment': group['comment'],
          'public': group['public'],
          'tests': group['tests'],
        },
  ];
  final json = const JsonEncoder.withIndent(
    '  ',
  ).convert({'testGroups': groups});

  File(_outputPath).writeAsStringSync('''
// Copyright 2026 Google LLC
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     https://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

// GENERATED BY tool/update_wycheproof_vectors.dart. DO NOT EDIT.
//
// The test groups with RSA keys from the Project Wycheproof JSON Web Signature
// test vectors, without their private keys:
// https://github.com/C2SP/wycheproof/blob/$_commit/$_vectorsPath

// ignore_for_file: lines_longer_than_80_chars

const wycheproofJsonWebSignatureVectors = r\'\'\'
$json
\'\'\';
''');

  final testCount = groups.fold(0, (count, group) {
    final tests = group['tests']! as List;
    return count + tests.length;
  });
  print('Wrote ${groups.length} groups ($testCount tests) to $_outputPath.');
}
